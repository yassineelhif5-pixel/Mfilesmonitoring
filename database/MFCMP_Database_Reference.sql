IF DB_ID(N'MFCMP') IS NULL CREATE DATABASE [MFCMP];
GO
/*
TABLE INVENTORY (dbo schema; physical schema generated by EF Core migrations)

dbo.AspNetUsers: portal users, password hashes, lockout and first-login password flag.
dbo.AspNetRoles, dbo.AspNetRoleClaims, dbo.AspNetUserClaims, dbo.AspNetUserLogins,
dbo.AspNetUserRoles, dbo.AspNetUserTokens: ASP.NET Core Identity roles and claims.

dbo.Vaults:
 Id uniqueidentifier PK; Name nvarchar(160); VaultGuid uniqueidentifier UNIQUE;
 CloudHost nvarchar(512); Organization nvarchar(160); Environment nvarchar(32);
 MonitoringEnabled bit; AuthenticationMode nvarchar(24);
 CredentialSecretUri nvarchar(2048) NULL (URI only, never secret value);
 AuthenticationPlugin nvarchar(160) NULL; AuthenticationScope nvarchar(512) NULL;
 HealthCheckIntervalSeconds int; MetricsCollectionIntervalMinutes int;
 CreatedAtUtc, UpdatedAtUtc datetimeoffset.

dbo.VaultHealthChecks:
 Id uniqueidentifier PK; VaultId FK -> Vaults.Id; CheckedAtUtc datetimeoffset;
 Status nvarchar(40); HttpStatusCode int NULL; DurationMs bigint;
 AuthenticationStatus nvarchar(40); AuthenticatedAccountName nvarchar(256) NULL;
 ServerVersion, CapabilitiesSummary; Message nvarchar(1000).

dbo.VaultDailyObjectStatistics:
 Id uniqueidentifier PK; VaultId FK -> Vaults.Id; DateUtc date;
 CreatedCount bigint; CreatedCountIsExact bit; TotalObjectCount bigint;
 TotalObjectCountIsExact bit; CollectedAtUtc datetimeoffset;
 UNIQUE (VaultId, DateUtc).

dbo.Incidents:
 Id uniqueidentifier PK; VaultId FK -> Vaults.Id; Category nvarchar(40);
 Severity nvarchar(8); Status nvarchar(24); Title nvarchar(200);
 Description nvarchar(2000); Fingerprint nvarchar(128);
 FirstSeenUtc, LastSeenUtc datetimeoffset; Occurrences int;
 AcknowledgedAtUtc, ResolvedAtUtc datetimeoffset NULL; LastErrorCode nvarchar(100) NULL.

dbo.__EFMigrationsHistory: EF Core migration ledger; do not edit manually.

Portal SQL stores monitoring metadata, health history, daily aggregate counts, incidents
and portal identities. It does not store M-Files document binaries. M-Files secrets stay
in Azure Key Vault; SQL stores only the secret URI.

EXAMPLE CONFIGURATION (replace SQLSERVER01; never commit passwords):
ConnectionStrings__DefaultConnection =
 Server=SQLSERVER01;Database=MFCMP;Integrated Security=True;Encrypt=True;
 TrustServerCertificate=False;MultipleActiveResultSets=True

SQL authentication alternative (password from secret store):
 Server=SQLSERVER01;Database=MFCMP;User Id=mfcmp_app;Password=<SECRET>;
 Encrypt=True;TrustServerCertificate=False;MultipleActiveResultSets=True

Deployment:
 dotnet ef database update --project backend/src/MFCMP.Api
Keep Database:ApplyMigrationsOnStartup=false in production and run migrations with a
dedicated deployment identity. Runtime identity should not be db_owner.
*/
